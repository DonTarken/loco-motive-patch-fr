$tsvPath = "translations\dialogues\prologue_french.tsv"

$addedCount = 0
$writer = [System.IO.File]::AppendText($tsvPath)

foreach ($row in $missingCsv) {
    $en = $row.Text.Trim()
    if ($translations.ContainsKey($en)) {
        $fr = $translations[$en]
        $char = $row.Character
        $cls = $row.Class
        $mth = $row.Method
        # Format: Id \t Character \t En \t Fr \t ClassName \t MethodName
        $line = "0`t$char`t$en`t$fr`t$cls`t$mth"
        $writer.WriteLine($line)
        $addedCount++
    }
}
$writer.Close()

